"""Shared helpers for the file-transfer tool (WarpSend v1.2).

Two checksum levels:
  * per-chunk CRC32  -- fast, catches a corrupt UDP packet at once
  * whole-file SHA-256 -- strong proof the received file is identical

v1.2 changes (from the 17 Nov 2026 code review):
  * Header validation: one `validate_header()` used by both
    modes (required keys, types, filesize >= 0, sane filename,
    64-hex checksum); `recv_header()` rejects a header longer
    than MAX_HEADER_BYTES instead of allocating gigabytes.
  * Protocol version: headers carry `"protocol": 2`. The old
    'wait 2 s for a reply that may never come' fallback is
    still there for pre-v1.1 servers, but v1.2 peers identify
    themselves.
  * Challenge-response auth: the HMAC now covers a per-connection
    nonce (TCP: a random challenge sent by the server; UDP: a
    random nonce generated by the client, rejected on replay
    within a server run), so a captured header cannot be replayed.
  * TLS 1.2 floor on both contexts, plus SSH-style trust on
    first use: fingerprints are remembered per host in
    ~/.warpsend/known_hosts.json and a changed fingerprint
    aborts loudly.
  * `.part` handling: `resume_offset()` now also reports a
    complete .part (size == filesize) so it can be verified
    and finalized instead of restarted; `claim_final_name()`
    claims the final name atomically with a hard link, closing
    the check-then-rename race.
  * Progress: `progress(..., base=offset)` computes speed/ETA
    from bytes moved in this session only, so a resume no
    longer inflates the speed; the bar goes to stderr so
    stdout stays machine-readable.

Only the standard library is used, so the tool runs with plain
``python3`` -- no pip install needed.
"""

