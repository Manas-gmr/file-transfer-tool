CHUNK_TCP = 256 * 1024     # 256 KB chunks for TCP (raised from 64 KB in v1.2)
CHUNK_UDP = 1024           # 1024 bytes of data per UDP packet
# (keeps each datagram well under the ~1400-byte practical limit,
#  so it is not fragmented on the network)

# A header is a small JSON object (filename, size, SHA-256, auth).
# Anything claiming to be larger is malformed, not a header.
MAX_HEADER_BYTES = 8192


def sha256_of_file(path, on_progress=None):
    """SHA-256 hex digest of a whole file, read in 64 KB pieces.

    `on_progress(done, total)` is called per chunk, so a caller
    can show that a large file is hashing instead of frozen.
    """
    h = hashlib.sha256()
    total = os.path.getsize(path)
    done = 0
    with open(path, "rb") as f:
        while chunk := f.read(64 * 1024):
            h.update(chunk)
            done += len(chunk)
            if on_progress:
                on_progress(done, total)
    return h.hexdigest()


def crc32_of(data: bytes) -> int:
    """CRC32 of one chunk (unsigned 32-bit int)."""
    return zlib.crc32(data) & 0xFFFFFFFF


# --- progress bar with speed + ETA (goes to stderr) -----------------------

_PROGRESS = {}  # label -> (start_time, base_bytes)


def _fmt_bytes(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.1f} {unit}" if unit != "B" else f"{int(n)} B"
        n /= 1024


def progress(done: int, total: int, label: str = "", base: int = 0) -> None:
    """One-line progress bar: [####------] 42% 1.2 MB / 3.0 MB  2.1 MB/s ETA 1s.

    Speed and ETA are computed from `done - base`, i.e. bytes
    moved in this session. On a resume, `base` is the offset
    already on disk, so the pre-existing bytes do not inflate
    the displayed speed.
    """
    if total <= 0:
        return
    now = time.monotonic()
    if label not in _PROGRESS or _PROGRESS[label][1] != base:
        _PROGRESS[label] = (now, base)
    start, _ = _PROGRESS[label]
    elapsed = max(now - start, 1e-6)
    moved = max(done - base, 0)
    rate = moved / elapsed if elapsed > 0.05 else 0
    eta = (total - done) / rate if rate > 0 else 0
    pct = done * 100 // total
    bar = "#" * (pct // 5) + "-" * (20 - pct // 5)
    speed = f"  {_fmt_bytes(rate)}/s" if rate else ""
    eta_s = f"  ETA {eta:.0f}s" if rate and done < total else ""
    print(f"\r{label} [{bar}] {pct:3d}%  {_fmt_bytes(done)} / {_fmt_bytes(total)}"
          f"{speed}{eta_s}", end="", flush=True, file=sys.stderr)
    if done >= total:
        print(file=sys.stderr)  # finish the line
        _PROGRESS.pop(label, None)


# --- length-prefixed JSON header (TCP) -------------------------------------
# A header is sent as:  4-byte big-endian length  +  JSON bytes.
# The length prefix tells the receiver exactly where the header
# ends and the file data begins.
#
# Header contents: {"filename": ..., "filesize": ..., "checksum": ...,
#                   "protocol": 2, "nonce": ..., "auth": ...}
#   checksum = SHA-256 of the whole file, computed by the sender.
#   nonce/auth are present only with --key (see below).

def send_header(sock, filename: str, filesize: int, checksum: str,
                auth: str | None = None, nonce: str | None = None) -> None:
    payload_dict = {
        "filename": filename,
        "filesize": filesize,
        "checksum": checksum,
        "protocol": PROTOCOL_VERSION,
    }
    if nonce:
        payload_dict["nonce"] = nonce
    if auth:
        payload_dict["auth"] = auth
    payload = json.dumps(payload_dict).encode()
    sock.sendall(struct.pack("!I", len(payload)) + payload)


def _recv_exact(sock, n: int) -> bytes:
    """Receive exactly n bytes (recv() may return fewer)."""
    buf = b""
    while len(buf) < n:
        part = sock.recv(n - len(buf))
        if not part:
            raise ConnectionError("connection closed while reading header")
        buf += part
    return buf


def recv_header(sock) -> dict:
    raw_len = _recv_exact(sock, 4)
    (length,) = struct.unpack("!I", raw_len)
    if length > MAX_HEADER_BYTES:
        raise ValueError(f"header length {length} exceeds "
                         f"maximum {MAX_HEADER_BYTES}")
    if length == 0:
        raise ValueError("empty header")
    return json.loads(_recv_exact(sock, length))


def validate_header(header) -> dict:
    """Validate an untrusted header; return its normalised fields.

    Raises ValueError on anything malformed: not a dict, missing
    keys, wrong types, negative filesize, empty/dot filename,
    NUL bytes, or a checksum that is not 64 hex characters.
    Callers use the returned dict, never the raw one.
    """
    if not isinstance(header, dict):
        raise ValueError("header is not a JSON object")
    for key in ("filename", "filesize", "checksum"):
        if key not in header:
            raise ValueError(f"header missing {key!r}")
    name = header["filename"]
    size = header["filesize"]
    checksum = header["checksum"]
    if not isinstance(name, str) or not name or "\x00" in name:
        raise ValueError("bad filename in header")
    name = os.path.basename(name)
    if name in ("", ".", ".."):
        raise ValueError("bad filename in header")
    if isinstance(size, bool) or not isinstance(size, int) or size < 0:
        raise ValueError("bad filesize in header")
    if (not isinstance(checksum, str) or len(checksum) != 64
            or any(c not in "0123456789abcdefABCDEF" for c in checksum)):
        raise ValueError("bad checksum in header")
    auth = header.get("auth")
    if auth is not None and not isinstance(auth, str):
        raise ValueError("bad auth tag in header")
    nonce = header.get("nonce")
    if nonce is not None and not isinstance(nonce, str):
        raise ValueError("bad nonce in header")
    protocol = header.get("protocol")
    if protocol is not None and protocol not in (1, 2):
        raise ValueError(f"unsupported protocol version {protocol!r}")
    return {"filename": name, "filesize": size,
            "checksum": checksum.lower(), "auth": auth,
            "nonce": nonce, "protocol": protocol or 1}


def recv_line(sock, timeout: float = 2.0):
    """Read one \\n-terminated line from a TCP socket.

    Returns the line without the newline, or None on timeout /
    closed connection. Used for the server's short replies
    (CHALLENGE / FRESH / RESUME <offset> / DONE / AUTH_FAIL /
    TOO_LARGE / INVALID). A timeout means the other side is a
    pre-v1.1 WarpSend that never sends a reply -- the caller
    should then assume a fresh transfer.
    """
    sock.settimeout(timeout)
    buf = b""
    try:
        while not buf.endswith(b"\n"):
            chunk = sock.recv(1)
            if not chunk:
                return None
            buf += chunk
            if len(buf) > 128:
                return None
    except (socket.timeout, TimeoutError):
        return None
    finally:
        sock.settimeout(None)
    return buf.decode(errors="replace").strip()


# --- shared-key auth (HMAC over the header + a nonce) ----------------------
# v1.2: the tag covers a per-connection nonce, so a header
# captured on the wire cannot be replayed for the same file.
# TCP: the nonce is the server's random challenge. UDP: the
# client generates a random nonce per transfer and the server
# rejects a nonce it has already seen in this run.

def header_auth(key: str, filename: str, filesize: int, checksum: str,
                nonce: str = "") -> str:
    """HMAC-SHA256 of the header fields under the shared secret."""
    msg = f"{nonce}\n{filename}\n{filesize}\n{checksum}".encode()
    return hmac_mod.new(key.encode(), msg, hashlib.sha256).hexdigest()


def auth_ok(key: str | None, header: dict, nonce: str = "") -> bool:
    """True if the header's auth matches the server's key.

    A server with no key accepts anything (backwards compatible).
    A server with a key rejects a missing or wrong auth tag.
    The nonce used is the one in the header if present, else
    the server's challenge nonce passed in here.
    """
    if not key:
        return True
    tag = header.get("auth")
    if not tag:
        return False
    use_nonce = header.get("nonce") or nonce
    return hmac_mod.compare_digest(
        tag, header_auth(key, header["filename"],
                         header["filesize"], header["checksum"], use_nonce))


# --- .part files, resume metadata, never-overwrite ------------------------

def part_path(outdir: str, name: str) -> str:
    return os.path.join(outdir, name + ".part")


def meta_path(outdir: str, name: str) -> str:
    return part_path(outdir, name) + ".json"


def save_meta(outdir: str, name: str, filesize: int, checksum: str) -> None:
    with open(meta_path(outdir, name), "w") as f:
        json.dump({"filename": name, "filesize": filesize,
                   "checksum": checksum}, f)


def load_meta(outdir: str, name: str):
    """Return the resume metadata for a .part file, or None."""
    try:
        with open(meta_path(outdir, name)) as f:
            meta = json.load(f)
        if (meta.get("filename") == name
                and isinstance(meta.get("filesize"), int)
                and meta.get("checksum")):
            return meta
    except (OSError, ValueError):
        pass
    return None


def resume_offset(outdir: str, name: str, filesize: int, checksum: str) -> int:
    """Bytes already on disk for this exact file, or 0.

    Only counts when the .part file and its metadata match the
    incoming file (same name, size and SHA-256). Anything else
    is a stale partial from a different file and is not resumed.
    A return of `filesize` (for a non-empty file) means the
    .part is complete and only needs its hash verified.
    """
    meta = load_meta(outdir, name)
    if not meta or meta["filesize"] != filesize or meta["checksum"] != checksum:
        return 0
    path = part_path(outdir, name)
    if not os.path.isfile(path):
        return 0
    size = os.path.getsize(path)
    if size > filesize:
        return 0
    return size


def unique_path(outdir: str, name: str) -> str:
    """A final path that never overwrites an existing file.

    `report.pdf` -> `report (1).pdf` -> `report (2).pdf` ...
    (A candidate name only; see claim_final_name for the
    atomic version used at rename time.)
    """
    path = os.path.join(outdir, name)
    if not os.path.exists(path):
        return path
    stem, dot, ext = name.rpartition(".")
    if not dot:  # no extension
        stem, ext = name, ""
    else:
        ext = "." + ext
    i = 1
    while True:
        candidate = os.path.join(outdir, f"{stem} ({i}){ext}")
        if not os.path.exists(candidate):
            return candidate
        i += 1


def claim_final_name(outdir: str, name: str) -> str:
    """Atomically claim a final name for a finished .part file.

    Tries each candidate with os.link(): creating the hard link
    fails if the name already exists, so no file created between
    the check and the rename can be silently replaced. On
    success the .part is unlinked and the claimed path returned.
    Falls back to os.rename when hard links are unavailable.
    """
    part = part_path(outdir, name)
    stem, dot, ext = name.rpartition(".")
    if not dot:
        stem, ext = name, ""
    else:
        ext = "." + ext
    candidates = [name] + [f"{stem} ({i}){ext}" for i in range(1, 1000)]
    for candidate in candidates:
        dest = os.path.join(outdir, candidate)
        try:
            os.link(part, dest)
        except FileExistsError:
            continue
        except OSError:
            if not os.path.exists(dest):
                os.rename(part, dest)
                return dest
            continue
        os.unlink(part)
        return dest
    raise OSError("could not claim a free final name")


def discard_part(outdir: str, name: str) -> None:
    for p in (part_path(outdir, name), meta_path(outdir, name)):
        try:
            os.remove(p)
        except OSError:
            pass


# --- TLS: self-signed certs, fingerprints, known hosts (TOFU) -------------

def default_cert_dir() -> str:
    return os.path.join(os.path.expanduser("~"), ".warpsend")


def default_cert_path() -> str:
    return os.path.join(default_cert_dir(), "cert.pem")


def default_key_path() -> str:
    return os.path.join(default_cert_dir(), "key.pem")


def default_known_hosts_path() -> str:
    return os.path.join(default_cert_dir(), "known_hosts.json")


def fingerprint_of_der(der: bytes) -> str:
    """SHA-256 fingerprint of a certificate, hex, no separators."""
    return hashlib.sha256(der).hexdigest()


def fingerprint_of_cert_file(cert_path: str) -> str:
    with open(cert_path, "rb") as f:
        pem = f.read()
    return fingerprint_of_der(ssl.PEM_cert_to_DER_cert(pem.decode()))


def short_code(fingerprint_hex: str) -> str:
    """6-digit code from the fingerprint, like Riptide's (123-456).

    Only ~20 bits of entropy -- a convenience check, not a
    replacement for comparing the full fingerprint.
    """
    code = int(fingerprint_hex[:6], 16) % 1_000_000
    return f"{code:06d}"[:3] + "-" + f"{code:06d}"[3:]


def load_known_hosts(path: str | None = None) -> dict:
    """host -> fingerprint, from the known-hosts file ({} if none)."""
    path = path or default_known_hosts_path()
    try:
        with open(path) as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def save_known_host(path: str | None, host: str, fingerprint_hex: str) -> None:
    """Remember a host's fingerprint (trust on first use)."""
    path = path or default_known_hosts_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    hosts = load_known_hosts(path)
    hosts[host] = fingerprint_hex
    with open(path, "w") as f:
        json.dump(hosts, f, indent=2, sort_keys=True)
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def generate_cert(cert_path: str | None = None, key_path: str | None = None):
    """Generate a self-signed RSA-2048 cert with the openssl binary.

    Returns (cert_path, key_path, fingerprint_hex). The private
    key is written with mode 0600. Raises RuntimeError if openssl
    is not available.
    """
    cert_path = cert_path or default_cert_path()
    key_path = key_path or default_key_path()
    os.makedirs(os.path.dirname(cert_path), exist_ok=True)
    result = subprocess.run(
        ["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes",
         "-keyout", key_path, "-out", cert_path, "-days", "3650",
         "-subj", "/CN=warpsend"],
        capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"openssl failed: {result.stderr.strip()}")
    os.chmod(key_path, 0o600)
    fp = fingerprint_of_cert_file(cert_path)
    return cert_path, key_path, fp


def server_tls_context(cert_path: str, key_path: str) -> ssl.SSLContext:
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.minimum_version = ssl.TLSVersion.TLSv1_2
    ctx.load_cert_chain(certfile=cert_path, keyfile=key_path)
    return ctx


def client_tls_context() -> ssl.SSLContext:
    # CERT_NONE at the library level: self-signed certs would be
    # rejected otherwise. The real check is the fingerprint
    # comparison done by the caller after the handshake, plus
    # the known-hosts file (trust on first use).
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.minimum_version = ssl.TLSVersion.TLSv1_2
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    return ctx


def peer_fingerprint(tls_sock) -> str:
    der = tls_sock.getpeercert(binary_form=True)
    return fingerprint_of_der(der) if der else ""
